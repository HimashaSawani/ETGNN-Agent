import { test, expect } from '@playwright/test';

/**
 * Live End-to-End Test with REAL FastAPI Backend (ZERO MOCKS)
 *
 * This test runs against the real FastAPI uvicorn server on port 8000
 * proxied through Vite preview on port 4173.
 *
 * It explicitly avoids all page.route() intercepts, ensuring all HTTP
 * requests travel from the browser -> Vite -> FastAPI -> PyTorch models -> SQLite.
 */

test.describe('Real FastAPI Backend Integration — Transaction 94340906', () => {
  test.beforeAll(async ({ request }) => {
    // Verify real backend is live and healthy before running browser tests
    const health = await request.get('http://127.0.0.1:8000/api/health');
    expect(health.status()).toBe(200);
    const json = await health.json();
    expect(json.status).toBe('healthy');
    expect(json.models_loaded).toContain('ETGNN');
  });

  test('Live browser-to-FastAPI investigation of Bitcoin transaction 94340906', async ({ page }) => {
    // Increase test timeout to accommodate real PyTorch GNN inference & LangGraph execution
    test.setTimeout(90000);

    const apiRequests: string[] = [];
    page.on('request', (req) => {
      const url = req.url();
      if (url.includes('/api/')) {
        apiRequests.push(`${req.method()} ${url}`);
      }
    });

    // 1. Navigate to live React SPA
    await page.goto('/');
    await expect(page).toHaveTitle(/ETGNN/i);

    // 2. Navigate to Model Predictions tab
    const predTab = page.getByRole('button', { name: /Model Predictions/i });
    await expect(predTab).toBeVisible();
    await predTab.click();

    // 3. Inspect target transaction 94340906
    const inspectInput = page.locator('.prediction-arena input[type="number"]');
    await expect(inspectInput).toBeVisible();
    await inspectInput.fill('94340906');

    const refreshBtn = page.getByRole('button', { name: /Refresh/i });
    await refreshBtn.click();

    // 4. Verify live transaction lookup and real model predictions
    // Transaction 94340906 is illicit ground-truth label 1
    await expect(page.getByText('Illicit (1)')).toBeVisible({ timeout: 15000 });

    // Verify model prediction cards rendered with real inference probabilities
    await expect(page.getByRole('heading', { name: 'ETGNN', exact: true })).toBeVisible();
    await expect(page.getByRole('heading', { name: 'Random Forest', exact: true })).toBeVisible();

    // 5. Open AI Investigation Copilot Drawer
    const investigateBtn = page.getByRole('button', { name: /Investigate with AI/i }).first();
    await expect(investigateBtn).toBeVisible();
    await investigateBtn.click();

    // Verify drawer visible and Tx ID synced
    await expect(page.getByText('ETGNN AI Investigation Copilot')).toBeVisible();
    const drawerTxInput = page.locator('.investigation-drawer input[type="number"]');
    await expect(drawerTxInput).toHaveValue('94340906');

    // 6. Select provider: EVIDENCE_ONLY (Deterministic Non-Generative Real Backend Execution)
    // Select dropdown 1 (Provider)
    const providerSelect = page.locator('.investigation-drawer select').nth(1);
    await providerSelect.selectOption('evidence_only');

    // 7. Launch Investigation on live backend
    const launchBtn = page.getByRole('button', { name: /Launch Investigation/i });
    await expect(launchBtn).toBeVisible();
    await launchBtn.click();

    // 8. Verify status updates through live LangGraph lifecycle to COMPLETED
    await expect(page.getByText('Status: COMPLETED', { exact: true })).toBeVisible({ timeout: 45000 });

    // 9. Verify forensic report sections generated by live backend
    await expect(page.getByText('Forensic Investigation Dossier')).toBeVisible();
    await expect(page.getByText('Snapshot 43', { exact: false }).first()).toBeVisible();

    // 10. Verify Evidence tab and real provenance chain
    const evidenceTab = page.locator('.investigation-drawer button:has-text("Evidence (")');
    await expect(evidenceTab).toBeVisible();
    await evidenceTab.click();

    // Verify evidence items loaded from real backend
    await expect(page.getByText('Evidence Records', { exact: false }).first()).toBeVisible();

    // 11. Capture live evidence screenshot
    await page.screenshot({
      path: 'playwright-report/live_real_backend_tx94340906.png',
      fullPage: true,
    });

    // 12. Verify that network requests genuinely reached the live backend
    expect(apiRequests.some((r) => r.includes('/api/transactions/94340906'))).toBe(true);
    expect(apiRequests.some((r) => r.includes('/api/agent/investigate'))).toBe(true);
  });
});

