                "    models_dict = manifest.get('scientific_inventory', {}).get('checkpoints', manifest.get('models', {}))\n",
                "    print(f'=== VERIFYING {len(models_dict)} MODEL CHECKPOINTS (SHA-256) ===')\n",
                "    \n",
                "    for model_name, meta in models_dict.items():\n",
                "        ck_rel = meta.get('path', meta.get('checkpoint_path'))\n",
